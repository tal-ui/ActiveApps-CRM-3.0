/**
 * Copy text, with a fallback that is required rather than belt-and-braces:
 * navigator.clipboard is undefined on insecure origins and unreliable in the
 * Capacitor WKWebView this app also ships in, and a copy button that silently
 * does nothing is worse than no copy button.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through */
  }
  try {
    const el = document.createElement("textarea");
    el.value = text;
    el.setAttribute("readonly", "");
    el.style.position = "fixed";
    el.style.opacity = "0";
    document.body.appendChild(el);
    el.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(el);
    return ok;
  } catch {
    return false;
  }
}
